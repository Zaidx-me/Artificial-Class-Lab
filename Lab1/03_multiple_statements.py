# Lab 1: Multiple Statements on a Single Line
# This program demonstrates using semicolons to write multiple statements

# Multiple assignment statements
a = 10; b = 20; c = 30
print("a =", a, ", b =", b, ", c =", c)

# Multiple print statements
print("Hello"); print("World"); print("!")

# Multiple operations
x = 5; y = 10; print("Sum:", x + y)

# Multiple conditional statements (not recommended but possible)
value = 42
if value > 0: print("Positive")
if value < 100: print("Less than 100")

# Demonstrating semicolon usage
name = "Python"; version = 3; print(name, "version", version)

# Note: While this works, it's generally better to write
# each statement on its own line for better readability
